/**
 * S2 服务驱动接口：网关之下的**唯一**存储抽象。
 *
 * # 为什么单独定义接口
 *
 * 网关的检查逻辑必须与"数据存在哪"解耦，否则每加一种引擎就要复制一遍门禁，
 * 而复制出来的门禁迟早漏一处。引擎接口只有 8 个方法，全部是**无授权概念**的
 * 纯数据操作——授权只在网关做一次。
 *
 * # 引擎**不**负责的事
 *
 * - 不做 scope 合法性校验（网关在构造 `DataScope` 时已保证）
 * - 不做配额判断（配额跨 scope 计量，引擎只看得见单条记录）
 * - 不做审计（引擎不知道调用者是谁）
 *
 * 这三件事若下沉到引擎，就会出现"memory 引擎做了、idb 引擎忘了"的漂移。
 *
 * # 错误约定
 *
 * 引擎抛 `StorageError`（`errors.ts` 的 `storageErrorOf`），**不抛裸 Error**。
 * 裸 Error 会被网关归一成 `STORAGE_UNAVAILABLE`，把"配额满"和"代码 bug"混成同一类。
 */
